WITH u AS (
  SELECT 'SALE_RK' AS SRC, t.CAT, TRIM(t.BRAND) AS BRAND_RAW, TRIM(t.URL) AS URL
  FROM `pjt-lge-oned.L2_ONED.VSMRKT_DAILY_OSM_SALE_RK_D` t
  WHERE t.DATE = DATE '2026-10-26' AND UPPER(TRIM(t.ONLINE_STR)) = 'MOMOSHOP'
    AND UPPER(TRIM(t.CAT)) IN ('WASHING MACHINE_HA','REFRIGERATOR_HA','DRYER_HA')
  UNION ALL
  SELECT 'BANR_VSBLT', t.CAT, TRIM(t.BRAND), TRIM(t.URL)
  FROM `pjt-lge-oned.L2_ONED.VSMRKT_DAILY_OSM_BANR_VSBLT_D` t
  WHERE t.DATE = DATE '2026-10-26' AND UPPER(TRIM(t.ONLINE_STR)) = 'MOMOSHOP'
    AND UPPER(TRIM(t.CAT)) IN ('WASHING MACHINE_HA','REFRIGERATOR_HA','DRYER_HA')
), x AS (
  SELECT *,
    REGEXP_REPLACE(UPPER(BRAND_RAW), r'^【?\s*([A-Z]+).*$', r'\1') AS BRAND_NORM,
    CASE WHEN REGEXP_CONTAINS(URL, r'/TP/') THEN 'TP' ELSE 'REGULAR' END AS URL_TYPE,
    REGEXP_REPLACE(REGEXP_REPLACE(REGEXP_REPLACE(URL, r'^.*[?&]i_code=(\d+).*$', r'\1'), r'^.*/product/(\d+).*$', r'\1'), r'^.*/goodsDetail/(TP\d+).*$', r'\1') AS PID
  FROM u
)
SELECT CAT, BRAND_NORM, URL_TYPE, PID,
  MIN(BRAND_RAW) AS BRAND_RAW_MIN,
  MAX(BRAND_RAW) AS BRAND_RAW_MAX,
  MIN(URL) AS URL_MIN,
  SUM(CASE WHEN UPPER(BRAND_RAW) IN ('LG','PANASONIC','SANLUX','WHIRLPOOL','HITACHI') THEN 1 ELSE 0 END) AS N_EXACT_BRAND,
  SUM(CASE WHEN SRC = 'SALE_RK' THEN 1 ELSE 0 END) AS N_SALE,
  COUNT(*) AS N
FROM x
WHERE BRAND_NORM IN ('LG','PANASONIC','SANLUX','WHIRLPOOL','HITACHI')
GROUP BY 1,2,3,4
ORDER BY 1,2,3,4
