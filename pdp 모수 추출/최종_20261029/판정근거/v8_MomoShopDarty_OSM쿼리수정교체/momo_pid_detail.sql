-- 상품번호마다 대표 1행(판매순위표 우선 → 순위 작은 것, 순위 없음은 뒤 → URL 순)의 상품명·모델코드·URL을 가져온다.
WITH u AS (
  SELECT 'SALE_RK' AS SRC, 1 AS PRI, t.CAT, TRIM(t.BRAND) AS BRAND_RAW, TRIM(t.URL) AS URL,
         TRIM(IFNULL(t.MPC,'')) AS MPC, TRIM(IFNULL(t.RPC,'')) AS RPC, t.PRODUCT_DESC, t.RK
  FROM `pjt-lge-oned.L2_ONED.VSMRKT_DAILY_OSM_SALE_RK_D` t
  WHERE t.DATE = DATE '2026-10-26' AND UPPER(TRIM(t.ONLINE_STR)) = 'MOMOSHOP'
    AND UPPER(TRIM(t.CAT)) IN ('WASHING MACHINE_HA','REFRIGERATOR_HA','DRYER_HA')
  UNION ALL
  SELECT 'BANR_VSBLT', 2, t.CAT, TRIM(t.BRAND), TRIM(t.URL),
         TRIM(IFNULL(t.MPC,'')), TRIM(IFNULL(t.RPC,'')), t.PRODUCT_DESC, t.RK
  FROM `pjt-lge-oned.L2_ONED.VSMRKT_DAILY_OSM_BANR_VSBLT_D` t
  WHERE t.DATE = DATE '2026-10-26' AND UPPER(TRIM(t.ONLINE_STR)) = 'MOMOSHOP'
    AND UPPER(TRIM(t.CAT)) IN ('WASHING MACHINE_HA','REFRIGERATOR_HA','DRYER_HA')
), x AS (
  SELECT *,
    CASE UPPER(TRIM(CAT)) WHEN 'WASHING MACHINE_HA' THEN 'W/M' WHEN 'REFRIGERATOR_HA' THEN 'REF' ELSE 'DRY' END AS DIV,
    REGEXP_REPLACE(UPPER(BRAND_RAW), r'^【?\s*([A-Z]+).*$', r'\1') AS BRAND_NORM,
    CASE WHEN REGEXP_CONTAINS(URL, r'/TP/') THEN 'TP' ELSE 'REGULAR' END AS URL_TYPE,
    REGEXP_REPLACE(REGEXP_REPLACE(REGEXP_REPLACE(URL, r'^.*[?&]i_code=(\d+).*$', r'\1'), r'^.*/product/(\d+).*$', r'\1'), r'^.*/goodsDetail/(TP\d+).*$', r'\1') AS PID
  FROM u
), f AS (
  SELECT * FROM x
  WHERE (DIV = 'REF' AND BRAND_NORM IN ('LG','PANASONIC','HITACHI','SANLUX'))
     OR (DIV IN ('W/M','DRY') AND BRAND_NORM IN ('LG','PANASONIC','SANLUX','WHIRLPOOL'))
)
SELECT URL_TYPE, PID, DIV, BRAND_NORM, BRAND_RAW, URL, MPC, RPC, PRODUCT_DESC, SRC, RK
FROM f
QUALIFY ROW_NUMBER() OVER (PARTITION BY URL_TYPE, PID ORDER BY PRI, RK IS NULL, RK, URL) = 1
ORDER BY URL_TYPE, PID
